#!/usr/bin/env python3
"""vibe-checkup mechanical scan.

Read-only. Collects cheap, deterministic signals from a project so the
agent spends its reading budget on judgement, not on grepping.

Usage: python scan.py <project_root> [--max N] [--section 0,3,8] [--since <commit>]
  --section  print only these sections (token saver: each sub-agent asks for its own)
  --since    limit §1-§3 (big files, pattern hits, secrets) to files changed since
             <commit> (working tree vs commit, plus untracked); §2 pattern hits are
             further limited to the changed lines of tracked files (untracked files
             count whole). §0 and §4-§8 are whole-project facts and are never
             filtered. A bad commit prints a warning and falls back to the whole project.
Output: Markdown on stdout. Every row is a *lead*, not a finding: the agent
must open the cited files before calling anything a finding. Anything that
looks like a secret is redacted before it is printed.
"""
